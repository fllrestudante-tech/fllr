CREATE TABLE asset_statistics_window (
  symbol TEXT NOT NULL,
  statistics_scope TEXT NOT NULL DEFAULT 'global',
  window_days INTEGER NOT NULL,
  window_candles INTEGER,
  coverage_pct REAL,
  freshness_score INTEGER,
  missing_rate REAL,
  duplicate_rate REAL,
  gap_rate REAL,
  sample_size INTEGER,
  effective_sample_size INTEGER,
  confidence INTEGER,
  version INTEGER NOT NULL DEFAULT 1,
  computed_at TEXT NOT NULL,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  PRIMARY KEY (symbol, statistics_scope, window_days)
);

